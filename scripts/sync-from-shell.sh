#!/usr/bin/env bash
# Pull the current mascot art from the live shell checkout into this repo
# and regenerate CATALOG.md. Review the git diff, commit, then cut a release
# with scripts/build-pack.sh.
set -euo pipefail

repo_dir="$(cd "$(dirname "$0")/.." && pwd)"
shell_mascot="${XDG_CONFIG_HOME:-$HOME/.config}/quickshell/inir/assets/images/mascot"

if [[ ! -d "$shell_mascot" ]]; then
  echo "error: shell mascot dir not found at ${shell_mascot}" >&2
  exit 1
fi

rsync -av --include='inir-mascot-*.png' --include='inir-mascot-*.gif' \
  --exclude='*' "$shell_mascot/" "$repo_dir/"
rsync -av --delete "$shell_mascot/frames/" "$repo_dir/frames/"

# Regenerate the visual catalog.
{
  echo "# Catalog"
  echo
  echo "Auto-generated by scripts/sync-from-shell.sh. Do not edit by hand."
  echo
  echo "## Animations"
  echo
  echo "| | | | |"
  echo "|---|---|---|---|"
  i=0
  for f in "$repo_dir"/inir-mascot-*.gif; do
    name="$(basename "$f" .gif)"; name="${name#inir-mascot-}"
    if ((i % 4 == 0)); then ((i > 0)) && echo; printf "|"; fi
    printf ' <img src="./%s" width="140"><br><sub>%s</sub> |' "$(basename "$f")" "$name"
    ((i++)) || true
  done
  echo
  echo
  echo "## Poses"
  echo
  echo "| | | | |"
  echo "|---|---|---|---|"
  i=0
  for f in "$repo_dir"/inir-mascot-*.png; do
    name="$(basename "$f" .png)"; name="${name#inir-mascot-}"
    if ((i % 4 == 0)); then ((i > 0)) && echo; printf "|"; fi
    printf ' <img src="./%s" width="140"><br><sub>%s</sub> |' "$(basename "$f")" "$name"
    ((i++)) || true
  done
  echo
} > "$repo_dir/CATALOG.md"

echo "synced. review with: git -C $repo_dir status"
