#!/usr/bin/env bash
# Regenerate the visual catalog from this repository's canonical art.
set -euo pipefail

repo_dir="$(cd "$(dirname "$0")/.." && pwd)"
mode="${1:-write}"
tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT

if [[ "$mode" != "write" && "$mode" != "--check" && "$mode" != "--stdout" ]]; then
  echo "usage: refresh-catalog.sh [--check|--stdout]" >&2
  exit 2
fi

shopt -s nullglob
animations=("$repo_dir"/inir-mascot-*.gif)
all_png=("$repo_dir"/inir-mascot-*.png)
chibi=("$repo_dir"/inir-mascot-chibi-*.png)
editorial=()
for pose in base expression-sheet hero-banner street-smoke-den street-scheme-station; do
  file="$repo_dir/inir-mascot-${pose}.png"
  [[ -f "$file" ]] && editorial+=("$file")
done

is_editorial() {
  local name="$(basename "$1")"
  case "$name" in
    inir-mascot-base.png|inir-mascot-expression-sheet.png|inir-mascot-hero-banner.png|inir-mascot-street-smoke-den.png|inir-mascot-street-scheme-station.png)
      return 0 ;;
    *) return 1 ;;
  esac
}

street=()
classic=()
for file in "${all_png[@]}"; do
  name="$(basename "$file")"
  if is_editorial "$file"; then
    continue
  elif [[ "$name" == inir-mascot-chibi-* ]]; then
    continue
  elif [[ "$name" == inir-mascot-street-* ]]; then
    street+=("$file")
  else
    classic+=("$file")
  fi
done

emit_table() {
  local title="$1"
  shift
  local files=("$@")
  echo "## $title"
  echo
  if ((${#files[@]} == 0)); then
    echo "_No assets in this group._"
    echo
    return
  fi
  echo "| | | | |"
  echo "|---|---|---|---|"
  local i=0 file name
  for file in "${files[@]}"; do
    name="$(basename "$file")"
    name="${name%.*}"
    name="${name#inir-mascot-}"
    if ((i % 4 == 0)); then
      ((i > 0)) && echo
      printf "|"
    fi
    printf ' <img src="./%s" width="140"><br><sub>%s</sub> |' "$(basename "$file")" "$name"
    ((i++)) || true
  done
  echo
  echo
}

{
  echo "# Catalog"
  echo
  echo "Auto-generated by scripts/refresh-catalog.sh. Do not edit by hand."
  echo
  echo "The catalog follows the runtime distinctions used by iNiR: animated loops,"
  echo "classic pixel cutouts, modern street cutouts, chibi reactions and editorial"
  echo "key art. Manual-only ratings remain documented in STREET.md."
  echo
  emit_table "Animations" "${animations[@]}"
  emit_table "Classic pixel poses" "${classic[@]}"
  emit_table "Street line" "${street[@]}"
  emit_table "Chibi reactions" "${chibi[@]}"
  emit_table "Editorial and key art" "${editorial[@]}"
} > "$tmp"

case "$mode" in
  --stdout)
    cat "$tmp"
    ;;
  --check)
    python3 "$repo_dir/scripts/validate.py"
    echo "catalog: complete"
    ;;
  write)
    mv "$tmp" "$repo_dir/CATALOG.md"
    trap - EXIT
    echo "catalog refreshed. review with: git -C $repo_dir status"
    ;;
esac
