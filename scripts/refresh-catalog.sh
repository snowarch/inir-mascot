#!/usr/bin/env bash
# Regenerate the visual catalog from this repository's canonical art.
set -euo pipefail

repo_dir="$(cd "$(dirname "$0")/.." && pwd)"

{
  echo "# Catalog"
  echo
  echo "Auto-generated by scripts/refresh-catalog.sh. Do not edit by hand."
  echo
  echo "## Animations"
  echo
  echo "| | | | |"
  echo "|---|---|---|---|"
  i=0
  for f in "$repo_dir"/inir-mascot-*.gif; do
    name="$(basename "$f" .gif)"; name="${name#inir-mascot-}"
    if ((i % 4 == 0)); then ((i > 0)) && echo; printf "|"; fi
    printf ' <img src="./%s" width="140"><br><sub>%s</sub> |' "$(basename "$f")" "$name"
    ((i++)) || true
  done
  echo
  echo
  echo "## Poses"
  echo
  echo "| | | | |"
  echo "|---|---|---|---|"
  i=0
  for f in "$repo_dir"/inir-mascot-*.png; do
    name="$(basename "$f" .png)"; name="${name#inir-mascot-}"
    if ((i % 4 == 0)); then ((i > 0)) && echo; printf "|"; fi
    printf ' <img src="./%s" width="140"><br><sub>%s</sub> |' "$(basename "$f")" "$name"
    ((i++)) || true
  done
  echo
} > "$repo_dir/CATALOG.md"

echo "catalog refreshed. review with: git -C $repo_dir status"
